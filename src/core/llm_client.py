class HuggingFaceLocalLLM:
    """Backward-compatible wrapper around HuggingFace Transformers text-generation pipeline."""

    def __init__(self, model_name: str = "distilgpt2", task: str = "text-generation"):
        self.model_name = model_name
        self.task = task
        self.generator = None

    def generate(
        self,
        prompt: str,
        max_length: int = 50,
        num_return_sequences: int = 1,
        **kwargs: Any,
    ) -> list[dict[str, str]]:
        """Generates text from input prompt using HuggingFace pipeline."""
        if self.generator is None:
            try:
                from transformers import pipeline

                self.generator = pipeline(self.task, model=self.model_name)
            except Exception:  # noqa: BLE001
                return [{"generated_text": prompt}]
        return self.generator(
            prompt,
            max_length=max_length,
            num_return_sequences=num_return_sequences,
            **kwargs,
        )


class BaseMultimodalLLMClient(abc.ABC):
    """Abstract base class for Multimodal Vision-Language Model clients."""

    def __init__(self, model: str, provider: str, api_key: str | None = None):
        """Initializes multimodal LLM client.

        Args:
            model: Model identifier string (e.g. 'gemini-2.0-flash', 'gpt-4o').
            provider: Provider name identifier ('gemini', 'claude', 'openai', 'mock').
            api_key: Optional API key for authenticating with provider endpoints.
        """
        self.model = model
        self.provider = provider
        self.api_key = api_key

    @abc.abstractmethod
    async def diagnose(
        self,
        prompt: str,
        image_bytes_base64: str,
        mime_type: str = "image/webp",
        system_prompt: str | None = None,
    ) -> tuple[DiagnosticReport, LLMUsageMetadata]:
        """Synthesizes a structured diagnostic report from multimodal screen and logcat context.

        Args:
            prompt: Text prompt with contextual logs, package info, and schema.
            image_bytes_base64: Base64-encoded image string of device viewport.
            mime_type: MIME image format (image/webp, image/jpeg, image/png).
            system_prompt: Optional role instruction. Defaults to STAFF_ANDROID_SYSTEM_PROMPT.

        Returns:
            Tuple of (DiagnosticReport, LLMUsageMetadata).
        """

    @staticmethod
    def extract_json(raw_text: str) -> dict[str, Any]:
        """Robustly extracts and parses a JSON object from raw LLM output.

        Handles markdown code blocks (```json ... ```), raw unformatted text,
        and surrounding conversational whitespace.

        Args:
            raw_text: Raw string generated by the language model.

        Returns:
            Parsed JSON dictionary.

        Raises:
            ValueError: If no valid JSON object structure can be extracted.
        """
        text = raw_text.strip()

        # 1. Direct parse attempt
        try:
            return json.loads(text)
        except json.JSONDecodeError:
            pass

        # 2. Extract from markdown code fences (```json ... ``` or ``` ... ```)
        fence_match = re.search(r"```(?:json)?\s*([\s\S]*?)\s*```", text, re.IGNORECASE)
        if fence_match:
            try:
                return json.loads(fence_match.group(1).strip())
            except json.JSONDecodeError:
                pass

        # 3. Locate outer-most JSON object braces '{' ... '}'
        start_idx = text.find("{")
        end_idx = text.rfind("}")
        if start_idx != -1 and end_idx != -1 and end_idx > start_idx:
            substring = text[start_idx : end_idx + 1]
            try:
                return json.loads(substring)
            except json.JSONDecodeError:
                pass

        raise ValueError(f"Failed to extract valid JSON from model response: {text[:200]}...")


class MockMultimodalClient(BaseMultimodalLLMClient):
    """Deterministic, zero-credential offline Mock VLM provider.

    Synthesizes realistic, schema-valid DiagnosticReport objects and telemetry metrics
    by analyzing incoming prompts for Android crash patterns and UI states.
    """

    def __init__(self, model: str = "mock-vlm-v1"):
        """Initializes mock VLM client with default model identifier."""
        super().__init__(model=model, provider="mock", api_key=None)

    async def diagnose(
        self,
        prompt: str,
        image_bytes_base64: str,
        mime_type: str = "image/webp",
        system_prompt: str | None = None,
    ) -> tuple[DiagnosticReport, LLMUsageMetadata]:
        """Synthesizes mock diagnostic report and usage telemetry deterministically.

        Inspects the incoming prompt for common Android exception markers (NPE, ANR,
        OOM) and constructs realistic root-cause analyses, crash signatures, and
        telemetry latency metrics without making external network calls.

        Args:
            prompt: Text prompt with contextual logs, package info, and schema.
            image_bytes_base64: Base64-encoded image string of device viewport.
            mime_type: MIME image format (image/webp, image/jpeg, image/png).
            system_prompt: Optional role instruction.

        Returns:
            Tuple of (DiagnosticReport, LLMUsageMetadata).
        """
        start_time = time.perf_counter()

        # Inspect prompt for crash indicators
        prompt_lower = prompt.lower()
        has_crash = any(
            k in prompt_lower
            for k in [
                "fatal exception",
                "nullpointerexception",
                "anr in",
                "crash_dialog",
                "outofmemoryerror",
                "classcastexception",
                "illegalstateexception",
            ]
        )

        # Extract target package name if present
        pkg_match = re.search(r"package\s*name:\s*([\w\.]+)", prompt, re.IGNORECASE)
        package_name = pkg_match.group(1) if pkg_match else "com.example.mobileapp"

        # Extract file/line if present
        file_match = re.search(r"([\w]+\.kt):(\d+)", prompt)
        crashing_file = file_match.group(1) if file_match else "FeedScreen.kt"
        crashing_line = int(file_match.group(2)) if file_match else 42

        if has_crash:
            if "nullpointerexception" in prompt_lower:
                exc_type = "java.lang.NullPointerException"
                exc_msg = "Attempt to invoke virtual method on a null object reference"
                root_cause = (
                    f"Fatal NullPointerException in '{package_name}' on thread main. "
                    f"The Composable at {crashing_file}:{crashing_line} attempted to dereference "
                    "a null state property prior to asynchronous data loading completion. "
                    "Screen inspection reveals the system crash alert dialog is active."
                )
                affected = [f"app/src/main/java/{package_name.replace('.', '/')}/ui/{crashing_file}:{crashing_line}"]
                fix = (
                    "Apply Kotlin safe navigation operator (?.) or supply a default loading state. "
                    "Ensure UI state collections utilize collectAsStateWithLifecycle()."
                )
            elif "anr in" in prompt_lower:
                exc_type = "android.os.ANRError"
                exc_msg = "Application Not Responding: Input dispatching timed out"
                root_cause = (
                    f"Application Not Responding (ANR) detected in '{package_name}'. "
                    "The main looper thread was blocked by long-running synchronous execution, "
                    "preventing input event dispatching within the 5000ms threshold."
                )
                affected = [f"app/src/main/java/{package_name.replace('.', '/')}/data/Repository.kt:85"]
                fix = (
                    "Offload heavy computations or I/O operations to CoroutineScope(Dispatchers.IO) "
                    "or withContext(Dispatchers.Default)."
                )
            else:
                exc_type = "java.lang.RuntimeException"
                exc_msg = "Fatal unhandled exception in application lifecycle"
                root_cause = (
                    f"Unhandled runtime exception detected in '{package_name}'. "
                    f"Failure observed at {crashing_file}:{crashing_line} resulting in abrupt activity termination."
                )
                affected = [f"app/src/main/java/{package_name.replace('.', '/')}/{crashing_file}:{crashing_line}"]
                fix = "Implement localized try-catch boundary and graceful error state handling."

            crash_sig = CrashSignature(
                exception_type=exc_type,
                exception_message=exc_msg,
                package_name=package_name,
                crashing_file=crashing_file,
                crashing_line=crashing_line,
                raw_stacktrace=(
                    f"FATAL EXCEPTION: main\n"
                    f"Process: {package_name}, PID: 4321\n"
                    f"{exc_type}: {exc_msg}\n"
                    f"\tat {package_name}.ui.{crashing_file.replace('.kt', 'Kt')}.render({crashing_file}:{crashing_line})\n"
                ),
            )
            report = DiagnosticReport(
                package_name=package_name,
                error_summary=f"FATAL EXCEPTION: {exc_type} in {crashing_file}:{crashing_line}",
                root_cause_analysis=root_cause,
                confidence_score=0.96,
                affected_components=affected,
                suggested_fix_summary=fix,
                crash_signature=crash_sig,
            )
        else:
            report = DiagnosticReport(
                package_name=package_name,
                error_summary="Application Running - No Fatal Crash Detected",
                root_cause_analysis=(
                    "Device screen viewport indicates active, responsive UI rendering. "
                    "Logcat sliding window shows healthy main looper cadence without unhandled exceptions or ANRs."
                ),
                confidence_score=0.92,
                affected_components=[],
                suggested_fix_summary="Continue runtime observation or trigger reproduction sequence.",
                crash_signature=None,
            )

        # Synthesize realistic token counts and duration
        latency_ms = max(round((time.perf_counter() - start_time) * 1000 + 45.0, 2), 1.0)
        prompt_tokens = max(len(prompt) // 4 + 256, 100)
        completion_tokens = 280
        total_tokens = prompt_tokens + completion_tokens

        usage = LLMUsageMetadata(
            provider=self.provider,
            model_name=self.model,
            prompt_tokens=prompt_tokens,
            completion_tokens=completion_tokens,
            total_tokens=total_tokens,
            latency_ms=latency_ms,
        )
        report.usage = usage
        return report, usage


class GeminiMultimodalClient(BaseMultimodalLLMClient):
    """Google Gemini Multimodal Client (gemini-2.0-flash, gemini-1.5-pro)."""

    def __init__(self, api_key: str | None = None, model: str = "gemini-2.0-flash"):
        """Initializes Gemini multimodal client.

        Args:
            api_key: Google GenAI API key. Defaults to GEMINI_API_KEY environment variable.
            model: Gemini model identifier (e.g. 'gemini-2.0-flash', 'gemini-1.5-pro').
        """
        key = api_key or os.getenv("GEMINI_API_KEY", "")
        super().__init__(model=model, provider="gemini", api_key=key)
        self.endpoint = (
            f"https://generativelanguage.googleapis.com/v1beta/models/{self.model}:generateContent"
        )

    async def diagnose(
        self,
        prompt: str,
        image_bytes_base64: str,
        mime_type: str = "image/webp",
        system_prompt: str | None = None,
    ) -> tuple[DiagnosticReport, LLMUsageMetadata]:
        """Dispatches multimodal diagnosis request to Google Gemini generateContent API.

        Constructs an inline data part for the base64 screen image, incorporates the
        triage prompt and system role instruction, requests JSON output format,
        and parses the returned candidate content into a DiagnosticReport.

        Args:
            prompt: Text prompt with contextual logs, package info, and schema.
            image_bytes_base64: Base64-encoded image string of device viewport.
            mime_type: MIME image format (image/webp, image/jpeg, image/png).
            system_prompt: Optional role instruction. Defaults to STAFF_ANDROID_SYSTEM_PROMPT.

        Returns:
            Tuple of (DiagnosticReport, LLMUsageMetadata).

        Raises:
            ValueError: If Gemini returns an empty candidate list or invalid JSON.
            httpx.HTTPStatusError: If the remote HTTP request fails.
        """
        start_time = time.perf_counter()
        sys_instruction = system_prompt or STAFF_ANDROID_SYSTEM_PROMPT

        payload = {
            "systemInstruction": {"parts": [{"text": sys_instruction}]},
            "contents": [
                {
                    "parts": [
                        {
                            "inlineData": {
                                "mimeType": mime_type,
                                "data": image_bytes_base64,
                            }
                        },
                        {"text": prompt},
                    ]
                }
            ],
            "generationConfig": {
                "responseMimeType": "application/json",
                "temperature": 0.2,
            },
        }

        async with httpx.AsyncClient(timeout=35.0) as client:
            resp = await client.post(
                self.endpoint,
                params={"key": self.api_key},
                json=payload,
                headers={"Content-Type": "application/json"},
            )
            resp.raise_for_status()
            data = resp.json()

        latency_ms = round((time.perf_counter() - start_time) * 1000, 2)

        # Parse text content from candidate
        candidates = data.get("candidates", [])
        if not candidates:
            raise ValueError(f"Gemini returned empty candidate list: {data}")
        raw_text = candidates[0].get("content", {}).get("parts", [{}])[0].get("text", "{}")
        parsed_dict = self.extract_json(raw_text)

        # Extract usage metadata
        usage_dict = data.get("usageMetadata", {})
        prompt_tokens = usage_dict.get("promptTokenCount", len(prompt) // 4)
        completion_tokens = usage_dict.get("candidatesTokenCount", len(raw_text) // 4)
        total_tokens = usage_dict.get("totalTokenCount", prompt_tokens + completion_tokens)

        usage = LLMUsageMetadata(
            provider=self.provider,
            model_name=self.model,
            prompt_tokens=prompt_tokens,
            completion_tokens=completion_tokens,
            total_tokens=total_tokens,
            latency_ms=latency_ms,
        )

        report = DiagnosticReport(**parsed_dict)
        report.usage = usage
        return report, usage


class ClaudeMultimodalClient(BaseMultimodalLLMClient):
    """Anthropic Claude Multimodal Client (claude-3-5-sonnet-20241022)."""

    def __init__(self, api_key: str | None = None, model: str = "claude-3-5-sonnet-20241022"):
        """Initializes Anthropic Claude multimodal client.

        Args:
            api_key: Anthropic API key. Defaults to ANTHROPIC_API_KEY environment variable.
            model: Claude model identifier (e.g. 'claude-3-5-sonnet-20241022').
        """
        key = api_key or os.getenv("ANTHROPIC_API_KEY", "")
        super().__init__(model=model, provider="claude", api_key=key)
        self.endpoint = "https://api.anthropic.com/v1/messages"

    async def diagnose(
        self,
        prompt: str,
        image_bytes_base64: str,
        mime_type: str = "image/webp",
        system_prompt: str | None = None,
    ) -> tuple[DiagnosticReport, LLMUsageMetadata]:
        """Dispatches multimodal diagnosis request to Anthropic Claude Messages API.

        Formats image payload as a base64 visual content block alongside the user triage prompt,
        specifies system instructions, and validates the response into a DiagnosticReport.

        Args:
            prompt: Text prompt with contextual logs, package info, and schema.
            image_bytes_base64: Base64-encoded image string of device viewport.
            mime_type: MIME image format (image/webp, image/jpeg, image/png).
            system_prompt: Optional role instruction. Defaults to STAFF_ANDROID_SYSTEM_PROMPT.

        Returns:
            Tuple of (DiagnosticReport, LLMUsageMetadata).

        Raises:
            ValueError: If Claude returns unparseable JSON content.
            httpx.HTTPStatusError: If the remote HTTP request fails.
        """
        start_time = time.perf_counter()
        sys_instruction = system_prompt or STAFF_ANDROID_SYSTEM_PROMPT

        # Map webp/jpeg/png to standard media types
        media_type = mime_type if mime_type in ["image/jpeg", "image/png", "image/webp", "image/gif"] else "image/webp"

        headers = {
            "x-api-key": self.api_key or "",
            "anthropic-version": "2023-06-01",
            "content-type": "application/json",
        }

        payload = {
            "model": self.model,
            "max_tokens": 2048,
            "system": sys_instruction,
            "messages": [
                {
                    "role": "user",
                    "content": [
                        {
                            "type": "image",
                            "source": {
                                "type": "base64",
                                "media_type": media_type,
                                "data": image_bytes_base64,
                            },
                        },
                        {"type": "text", "text": prompt},
                    ],
                }
            ],
        }

        async with httpx.AsyncClient(timeout=35.0) as client:
            resp = await client.post(self.endpoint, headers=headers, json=payload)
            resp.raise_for_status()
            data = resp.json()

        latency_ms = round((time.perf_counter() - start_time) * 1000, 2)

        content_parts = data.get("content", [])
        raw_text = "".join(part.get("text", "") for part in content_parts if part.get("type") == "text")
        parsed_dict = self.extract_json(raw_text)

        usage_info = data.get("usage", {})
        prompt_tokens = usage_info.get("input_tokens", len(prompt) // 4)
        completion_tokens = usage_info.get("output_tokens", len(raw_text) // 4)
        total_tokens = prompt_tokens + completion_tokens

        usage = LLMUsageMetadata(
            provider=self.provider,
            model_name=self.model,
            prompt_tokens=prompt_tokens,
            completion_tokens=completion_tokens,
            total_tokens=total_tokens,
            latency_ms=latency_ms,
        )

        report = DiagnosticReport(**parsed_dict)
        report.usage = usage
        return report, usage


class OpenAIMultimodalClient(BaseMultimodalLLMClient):
    """OpenAI Multimodal Client (gpt-4o, gpt-4o-mini)."""

    def __init__(self, api_key: str | None = None, model: str = "gpt-4o"):
        """Initializes OpenAI multimodal client.

        Args:
            api_key: OpenAI API key. Defaults to OPENAI_API_KEY environment variable.
            model: OpenAI model identifier (e.g. 'gpt-4o', 'gpt-4o-mini').
        """
        key = api_key or os.getenv("OPENAI_API_KEY", "")
        super().__init__(model=model, provider="openai", api_key=key)
        self.endpoint = "https://api.openai.com/v1/chat/completions"

    async def diagnose(
        self,
        prompt: str,
        image_bytes_base64: str,
        mime_type: str = "image/webp",
        system_prompt: str | None = None,
    ) -> tuple[DiagnosticReport, LLMUsageMetadata]:
        """Dispatches multimodal diagnosis request to OpenAI Chat Completions API.

        Submits base64 image data via image_url payload, enforces JSON output via
        response_format={"type": "json_object"}, and parses token usage and diagnostic findings.

        Args:
            prompt: Text prompt with contextual logs, package info, and schema.
            image_bytes_base64: Base64-encoded image string of device viewport.
            mime_type: MIME image format (image/webp, image/jpeg, image/png).
            system_prompt: Optional role instruction. Defaults to STAFF_ANDROID_SYSTEM_PROMPT.

        Returns:
            Tuple of (DiagnosticReport, LLMUsageMetadata).

        Raises:
            ValueError: If OpenAI returns empty choices or unparseable JSON content.
            httpx.HTTPStatusError: If the remote HTTP request fails.
        """
        start_time = time.perf_counter()
        sys_instruction = system_prompt or STAFF_ANDROID_SYSTEM_PROMPT

        headers = {
            "Authorization": f"Bearer {self.api_key}",
            "Content-Type": "application/json",
        }

        payload = {
            "model": self.model,
            "response_format": {"type": "json_object"},
            "messages": [
                {"role": "system", "content": sys_instruction},
                {
                    "role": "user",
                    "content": [
                        {"type": "text", "text": prompt},
                        {
                            "type": "image_url",
                            "image_url": {
                                "url": f"data:{mime_type};base64,{image_bytes_base64}"
                            },
                        },
                    ],
                },
            ],
        }

        async with httpx.AsyncClient(timeout=35.0) as client:
            resp = await client.post(self.endpoint, headers=headers, json=payload)
            resp.raise_for_status()
            data = resp.json()

        latency_ms = round((time.perf_counter() - start_time) * 1000, 2)

        choices = data.get("choices", [])
        if not choices:
            raise ValueError(f"OpenAI returned empty choices: {data}")
        raw_text = choices[0].get("message", {}).get("content", "{}")
        parsed_dict = self.extract_json(raw_text)

        usage_info = data.get("usage", {})
        prompt_tokens = usage_info.get("prompt_tokens", len(prompt) // 4)
        completion_tokens = usage_info.get("completion_tokens", len(raw_text) // 4)
        total_tokens = usage_info.get("total_tokens", prompt_tokens + completion_tokens)

        usage = LLMUsageMetadata(
            provider=self.provider,
            model_name=self.model,
            prompt_tokens=prompt_tokens,
            completion_tokens=completion_tokens,
            total_tokens=total_tokens,
            latency_ms=latency_ms,
        )

        report = DiagnosticReport(**parsed_dict)
        report.usage = usage
        return report, usage


def get_multimodal_client(
    provider: str | None = None,
    model: str | None = None,
) -> BaseMultimodalLLMClient:
    """Factory creating configured multimodal LLM client with graceful offline fallback.

    Args:
        provider: Provider identifier ('gemini', 'claude', 'openai', 'mock').
        model: Specific model name identifier.

    Returns:
        Configured BaseMultimodalLLMClient instance.
    """
    req_provider = (provider or "").strip().lower()

    # Explicit provider requested
    if req_provider == "gemini":
        gemini_key = os.getenv("GEMINI_API_KEY")
        if gemini_key:
            return GeminiMultimodalClient(api_key=gemini_key, model=model or "gemini-2.0-flash")
        logger.warning("GEMINI_API_KEY missing. Falling back to MockMultimodalClient.")
        return MockMultimodalClient(model=model or "mock-vlm-fallback")

    if req_provider in ["claude", "anthropic"]:
        anthropic_key = os.getenv("ANTHROPIC_API_KEY")
        if anthropic_key:
            return ClaudeMultimodalClient(api_key=anthropic_key, model=model or "claude-3-5-sonnet-20241022")
        logger.warning("ANTHROPIC_API_KEY missing. Falling back to MockMultimodalClient.")
        return MockMultimodalClient(model=model or "mock-vlm-fallback")

    if req_provider == "openai":
        openai_key = os.getenv("OPENAI_API_KEY")
        if openai_key:
            return OpenAIMultimodalClient(api_key=openai_key, model=model or "gpt-4o")
        logger.warning("OPENAI_API_KEY missing. Falling back to MockMultimodalClient.")
        return MockMultimodalClient(model=model or "mock-vlm-fallback")

    if req_provider == "mock":
        return MockMultimodalClient(model=model or "mock-vlm-v1")

    # Implicit provider resolution via environment presence
    if os.getenv("GEMINI_API_KEY"):
        return GeminiMultimodalClient(model=model or "gemini-2.0-flash")
    if os.getenv("ANTHROPIC_API_KEY"):
        return ClaudeMultimodalClient(model=model or "claude-3-5-sonnet-20241022")
    if os.getenv("OPENAI_API_KEY"):
        return OpenAIMultimodalClient(model=model or "gpt-4o")

    # Default zero-credential fallback
    return MockMultimodalClient(model=model or "mock-vlm-v1")
